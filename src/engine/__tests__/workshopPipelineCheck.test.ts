import assert from "node:assert/strict";
import { designPipeline } from "../designer";
import { checkWorkshopPipeline } from "../workshopPipelineCheck";

const design = designPipeline({ family: "narrated_stock", nicheKey: "history", lengthMinutes: 5, publishMode: "draft" });
const pipeline = design.pipeline.map(entry => entry.block === "narration_tts" ? { ...entry, params: { ...entry.params, ttsProvider: "qwen3", qwenSpeaker: "Serena" } } : entry);
const result = checkWorkshopPipeline("narrated_stock", pipeline);
assert.equal(result.lane, "narrated_documentary");
assert.equal(result.modules.length, pipeline.length);
assert.match(result.fingerprint, /^[a-f0-9]{64}$/);
assert.ok(Number.isFinite(result.reservedMaxCostUsd) && result.reservedMaxCostUsd > 0);
assert.throws(() => checkWorkshopPipeline("not-a-format", pipeline), /supported video format/);
assert.throws(() => checkWorkshopPipeline("narrated_stock", []), /pipeline is empty/);
assert.throws(() => checkWorkshopPipeline("narrated_stock", [{ block: "not_a_module" }]), /unknown block/);
assert.throws(() => checkWorkshopPipeline("narrated_stock", design.pipeline), /explicit Qwen3 narration/);
assert.throws(() => checkWorkshopPipeline("narrated_stock", pipeline.map(entry => entry.block === "narration_tts" ? { ...entry, params: { ttsProvider: "elevenlabs" } } : entry)), /explicit Qwen3 narration/);
const withoutVisuals = pipeline.filter(entry => entry.block !== "stock_footage");
assert.throws(() => checkWorkshopPipeline("narrated_stock", withoutVisuals));
assert.throws(() => checkWorkshopPipeline("music_loop", pipeline));
console.log("Workshop compiler check: valid pipeline passes; unknown, incomplete and wrong-format drafts fail");
